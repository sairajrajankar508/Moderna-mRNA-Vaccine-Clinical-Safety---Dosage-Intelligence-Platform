def fallback_banner(manifest: dict, provider: str) -> list[str]:
    issues = []
    if "fallback" in manifest["embedding_model"]:
        issues.append(f"retrieval used the offline hashing embedder (`{manifest['embedding_model']}`) instead of a sentence-embedding model")
    if "fallback" in manifest["store_backend"]:
        issues.append("the vector index used the NumPy fallback store instead of ChromaDB")
    if provider.startswith("offline"):
        issues.append("reports were drafted by the offline rule-based generator, not an LLM")
    if not issues:
        return []
    return ["> **Note: these results come from offline fallbacks.** In this run " + "; ".join(issues) + ". "
            "Install the full requirements, set an LLM API key in `.env`, run `python main.py all --rebuild`, "
            "and this report regenerates with the final numbers.", ""]


def module1_section(meta: dict, comparison: pd.DataFrame, weights: pd.DataFrame) -> list[str]:
    best = meta["selected_model"]
    other = next(n for n in NAMES if n != best)
    rows = {r.model: r for r in comparison.itertuples()}
    b, o = rows[best], rows[other]
    cm = pd.read_csv(METRICS_DIR / f"{best}_confusion_matrix.csv", index_col=0).values
    tn, fp, fn, tp = cm.ravel()
    top = weights.iloc[0]
    weight_col = weights.columns[1]
    table = ["| Model | Test F1 (High risk) | Test ROC-AUC | Test accuracy | 5-fold CV F1 (train) | Tuned parameters |",
             "|---|---|---|---|---|---|"]
    for r in comparison.itertuples():
        params = ", ".join(f"{k}={v}" for k, v in json.loads(r.best_params).items())
        table.append(f"| {NAMES[r.model]}{' (selected)' if r.selected else ''} | {r.test_f1:.3f} | {r.test_roc_auc:.3f} | "
                     f"{r.test_accuracy:.3f} | {r.cv_f1:.3f} | {params} |")
    feats = ", ".join(f"{w.feature} ({getattr(w, weight_col):+.2f})" if weight_col == "coefficient"
                      else f"{w.feature} ({getattr(w, weight_col):.2f})" for w in weights.itertuples())

    if best == "logistic_regression":
        why = ("The simpler model winning is a sign that the signal in this data is mostly additive: each risk factor "
               "pushes the probability up on its own, which is exactly the shape a logistic regression assumes. The "
               "Random Forest can model interactions, but with only 400 noisy training rows the extra flexibility "
               "mostly fits noise"
               + (", and its cross-validation F1 was also lower." if o.cv_f1 < b.cv_f1 else
                  ". Its cross-validation F1 was slightly higher, though, so the gap is within noise for a 100-row test set."))
    else:
        why = ("The Random Forest's advantage suggests some non-linear structure or interactions between features "
               "(for example dose mattering more for older patients) that a linear model cannot represent.")

    return [
        "## 3. Module 1 results: risk classifier",
        "",
        "The 500-record dataset had 20 missing biomarker values (4.0%) and 17 missing reaction histories (3.4%). "
        "Biomarker gaps were filled with the median and reaction-history gaps with the mode. One data trap was "
        "important: pandas reads the text `None` as a missing value by default, which would have turned 291 "
        "real \"no prior reaction\" patients into blanks. The loader treats only empty cells as missing.",
        "",
        *table,
        "",
        f"![Confusion matrix]({FIG}/final_model_confusion_matrix.png)",
        "",
        f"**Interpretation.** On the 100 held-out patients the selected {NAMES[best]} caught {tp} of {tp + fn} "
        f"high-risk patients (recall {tp / (tp + fn):.0%}) and {fp} of the {tn + fp} low-risk patients were flagged "
        f"unnecessarily. The strongest feature is {top.feature}. Feature weights: {feats}"
        + (" (coefficients on standardized inputs, except Pre_Existing_Conditions per condition and reaction history per severity step)."
           if weight_col == "coefficient" else " (impurity importances)."),
        "",
        f"**Model comparison.** {NAMES[best]} reached a test F1 of {b.test_f1:.3f} against {o.test_f1:.3f} for the "
        f"{NAMES[other]}, and a ROC-AUC of {b.test_roc_auc:.3f} against {o.test_roc_auc:.3f}, so it was selected and "
        f"saved to `outputs/risk_model.joblib`. {why} Both models land in the 0.65-0.80 range the PRD calls "
        "believable for this deliberately noisy data; a much higher score would suggest leakage. In a clinical "
        "setting recall on the High-risk class matters most, so a lower decision threshold would be worth exploring.",
        "",
        "EDA figures: "
        f"[distributions]({FIG}/eda_distributions.png), [correlation heatmap]({FIG}/eda_correlation_heatmap.png), "
        f"[class balance]({FIG}/eda_class_balance.png), [risk by prior reaction]({FIG}/eda_reaction_history.png).",
        "",
    ]


def module2_section(attention: dict) -> list[str]:
    seq = attention["sequence"]
    pairs = list(attention["base_pair_attention"].items())
    (p1, v1), (p2, v2) = pairs[0], pairs[1]
    low_pair, low_v = pairs[-1]
    uniform = 1 / len(seq)
    return [
        "## 4. Module 2 results: self-attention on an mRNA sequence",
        "",
        f"![Attention heatmap]({FIG}/attention_heatmap.png)",
        "",
        f"Sequence `{seq}` ({len(seq)} bases), 8-dimensional embeddings, one attention head. Every row of the "
        f"{len(seq)}x{len(seq)} matrix sums to 1.",
        "",
        "**What the heatmap shows.** Each base is first turned into an 8-number embedding vector. Three weight "
        "matrices then turn every embedding into a query (what this position is looking for), a key (what it "
        "offers to others) and a value (the information it passes on). The score between positions i and j is "
        "the dot product of query i with key j, divided by the square root of the key size so that scores stay "
        "around unit scale. A softmax turns each row of scores into percentages that add up to 100%, and the output "
        "for each position is the matching blend of value vectors. In the heatmap, row i shows where position i "
        f"sends its attention. The strongest pattern is {p1} (mean weight {v1:.3f}) followed by {p2} ({v2:.3f}), "
        f"compared with {uniform:.3f} if attention were spread evenly; the weakest is {low_pair} ({low_v:.3f}). "
        "Rows for the same base are identical, and so are columns, because no positional information is added: "
        "the model only knows which base sits at a position, not where it is. The preferences themselves are not "
        "biology. The weights were randomly initialized and never trained, so they reflect which random embedding "
        "vectors happen to line up after projection. Training on a real task, plus positional encodings (already "
        "implemented as an option), would make the pattern meaningful.",
        "",
        "Multi-head attention (the bonus task) is implemented in `multi_head_attention()` and tested with 2 and 4 heads.",
        "",
    ]


def _failure_case(results: dict, chunks_by_text: dict) -> list[str]:
    misses = [r for r in results["standard"] if not r["hit"]] + [r for r in results["stress"] if not r["hit"]]
    if not misses:
        return ["**Failure case.** Every test question returned the answering chunk first in this run, so no outright "
                "failure was observed. The weakest result was the question with the lowest top similarity; the "
                "paraphrase stress set is where a weaker embedder fails first."]
    r = misses[0]
    q_words = _words(r["question"])
    answer_sentence = next((s for s in chunks_by_text["sentences"] if r["phrase"].lower() in s.lower()), "")
    in_answer = sorted(q_words & _words(answer_sentence))
    rank = f"ranked {r['answer_rank']}" if r["answer_rank"] else "not retrieved at all (outside the top 3)"
    overlap = (f"only {', '.join(in_answer)} also appear{'s' if len(in_answer) == 1 else ''} in the answering sentence"
               if in_answer else "none appear in the answering sentence")
    return [
        f"**Failure case.** *\"{r['question']}\"* The answer (\"{r['phrase']}\") is in {r['expected']}, but the top "
        f"chunk covered {r['top_sections']} and the answering chunk was {rank}. Hypothesis: of the question's content "
        f"words ({', '.join(sorted(q_words))}), {overlap}. "
        + ("The hashing embedder can only match identical words, so a question phrased differently from the "
           "guideline has little to match on, and chunks that merely share common words such as *vial* or *dose* "
           "win instead. A semantic embedding model should "
           "fix this; compare after rerunning with the full requirements."
           if "fallback" in chunks_by_text["embedder"] else
           "Even a semantic model compresses a whole 300-500 token chunk into one vector, so a chunk that mostly "
           "discusses something else can outrank the chunk holding a single relevant sentence. Smaller chunks or "
           "re-ranking the top results would help."),
        "",
        f"Misses in this run: {len([m for m in results['standard'] if not m['hit']])} of {len(results['standard'])} standard "
        f"questions and {len([m for m in results['stress'] if not m['hit']])} of {len(results['stress'])} paraphrased questions.",
    ]


def module3_section(manifest: dict) -> list[str]:
    import rag_index as rag
    from guardrails import guideline_sentences

    index = rag.load_index(log_path=None)
    results = {"standard": rag.evaluate_questions(index, rag.TEST_QUESTIONS),
               "stress": rag.evaluate_questions(index, rag.STRESS_QUESTIONS)}
    text = (ROOT / "data" / "mrna_safety_guidelines.txt").read_text(encoding="utf-8")
    context = {"sentences": guideline_sentences(text), "embedder": manifest["embedding_model"]}
    chunk_rows = ["| Chunk | Tokens | Overlap with previous |", "|---|---|---|"]
    chunk_rows += [f"| {i} | {t} | {o} |" for i, (t, o) in enumerate(zip(manifest["chunk_tokens"], manifest["overlap_tokens"]))]
    q_rows = ["| Question | Top chunk covers | Hit@1 | Latency (s) |", "|---|---|---|---|"]
    q_rows += [f"| {r['question']} | {r['top_sections']} | {'yes' if r['hit'] else '**no**'} | {r['latency_s']:.4f} |"
               for r in results["standard"]]
    hits = sum(r["hit"] for r in results["standard"])
    doc_tokens = rag.count_tokens(text)
    return [
        "## 5. Module 3 results: retrieval over the safety guidelines",
        "",
        f"Embedding model `{manifest['embedding_model']}`, store `{manifest['store_backend']}`, "
        f"{manifest['n_chunks']} chunks, k = 3. Full tables, including a paraphrase stress test: "
        "[`outputs/rag_test_queries.md`](../outputs/rag_test_queries.md).",
        "",
        *chunk_rows,
        "",
        f"Top-ranked chunk contains the answering sentence for **{hits} of {len(results['standard'])}** standard questions:",
        "",
        *q_rows,
        "",
        f"**Chunk size and overlap.** The document is short (about {doc_tokens:,} tokens), so chunks target about 350 tokens, "
        "the lower part of the required 300-500 range. That gives four chunks instead of two or three: with k = 3, a "
        "two-chunk index would return the whole document for every query and retrieval would test nothing. Chunks "
        "are built from whole sentences so no rule is cut in half, and the last sentences of each chunk (about 50 "
        "tokens) are repeated at the start of the next, so a clause near a boundary is complete in at least one "
        "chunk. LangChain's splitter enforces only a maximum size, so a custom sentence packer guarantees the 300-token "
        "minimum; the final chunk is grown backwards when needed, which is why its overlap is larger. The embedding "
        "model is `BAAI/bge-small-en-v1.5` rather than `all-MiniLM-L6-v2` because MiniLM truncates input at 256 "
        "word-pieces, which would silently drop the end of every 300-500 token chunk.",
        "",
        *_failure_case(results, context),
        "",
    ]


def module4_section(generation: pd.DataFrame) -> list[str]:
    reports = sorted(REPORTS_DIR.glob("*_report.json"))
    summary = ["| Patient | Eligible | Dose (mg) | Rules triggered |", "|---|---|---|---|"]
    latest = generation.drop_duplicates("patient_id", keep="last").set_index("patient_id")
    for path in reports:
        pid = path.name.replace("_report.json", "")
        data = json.loads(path.read_text(encoding="utf-8"))
        rules = latest.loc[pid, "rules_triggered"] if pid in latest.index else ""
        rules = rules if isinstance(rules, str) and rules else "none"
        summary.append(f"| {pid} | {'yes' if data['Eligible_For_Vaccine'] else 'no'} | {data['Recommended_Dose_mg']:g} | {rules} |")

    eligible = [p for p in reports if json.loads(p.read_text(encoding="utf-8"))["Eligible_For_Vaccine"]]
    capped = [p for p in eligible if "lowered" in p.read_text(encoding="utf-8")]
    showcase = (capped or eligible or reports)[0]
    pid = showcase.name.replace("_report.json", "")
    sample = json.loads(showcase.read_text(encoding="utf-8"))
    provider = generation["provider"].iloc[-1]

    annotations = []
    for i, step in enumerate(sample["Reasoning_Steps"], 1):
        if "risk model" in step:
            source = "Module 1 risk output"
        elif step.startswith("[Safety check]"):
            source = "deterministic guardrail (guardrails.py)"
        else:
            source = "retrieved guideline excerpt (Module 3), cited below"
        annotations.append(f"| {i} | {source} |")

    return [
        "## 6. Module 4 results: structured safety report",
        "",
        f"Reports were generated by `{provider}`. Every response is parsed as JSON and validated against the strict "
        "`ClinicalSafetyReport` schema, with exactly one retry on failure. A deterministic guardrail layer then checks "
        "the dose against the bound parsed from the retrieved text (FR-4.4), applies the secondary-review clauses, "
        "removes citations that are not verbatim guideline text, and forces the disclaimer. Guardrails can only make "
        "a decision more conservative, never less.",
        "",
        *summary,
        "",
        f"Full sample (`outputs/reports/{showcase.name}`):",
        "",
        "```json",
        json.dumps(sample, indent=2),
        "```",
        "",
        "How each reasoning step is grounded:",
        "",
        "| Step | Source |",
        "|---|---|",
        *annotations,
        "",
        "Each entry in `FDA_Safety_Warnings_Cited` was checked to appear word for word in the retrieved chunks. "
        f"`Recommended_Dose_mg` is {sample['Recommended_Dose_mg']:g} mg = {sample['Recommended_Dose_mg'] * 1000:g} mcg "
        "(the PRD's field is in milligrams while the data uses micrograms).",
        "",
    ]


def limitations_section(manifest: dict) -> list[str]:
    return [
        "## 8. Limitations and future work",
        "",
        "1. **Small, synthetic dataset.** 500 rows and 5 features cap the classifier near 0.7 F1, and with a 100-row "
        "test set one patient moves F1 by about 1%. With more time: repeated cross-validation for tighter estimates, "
        "probability calibration, and choosing the decision threshold for high recall on the High-risk class.",
        f"2. **Retrieval granularity.** With {manifest['n_chunks']} chunks and k = 3 the retriever returns most of the "
        "document, so precision@1 is the only meaningful metric, and chunk vectors dilute single-sentence rules. "
        "Sentence-level indexing with a cross-encoder re-ranker, or hybrid BM25 + dense search, would sharpen it.",
        "3. **Rules are partly hand-coded.** Guardrail rules are linked to guideline clauses by regex, and the "
        "biomarker threshold (10 mg/L) is a project assumption because the guideline gives no number. A real system "
        "would take thresholds from a versioned clinical rules source signed off by clinicians.",
        "4. **LLM cost and latency.** Each report is one or two LLM calls (seconds each, see the dashboard), so a batch "
        "of thousands of patients would be slow and paid. Caching retrieval per patient profile and using the offline "
        "generator for clear-cut cases would cut both.",
        "5. **Attention module is untrained.** It demonstrates the mechanism, but its weights are random, so the "
        "heatmap carries no biological meaning. Training it on a sequence task (for example predicting masked bases) "
        "would be the next step.",
        "",
    ]


