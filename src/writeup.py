def build():
    meta, comparison, weights, attention, manifest, generation = _load()
    provider = generation["provider"].iloc[-1]
    best = meta["selected_model"]
    best_row = comparison[comparison.model == best].iloc[0]
    lines = [
        MARKER,
        "",
        "# mRNA Vaccine Clinical Safety & Dosage Intelligence Platform: project report",
        "",
        f"*Generated {datetime.now().strftime('%d %B %Y')} from the files in `outputs/`.*",
        "",
        "> **Disclaimer:** student engineering project on synthetic data. Nothing here is real clinical or "
        "regulatory guidance. This is a case study that references Moderna's public mRNA work; it is not affiliated "
        "with or endorsed by Moderna.",
        "",
        *fallback_banner(manifest, provider),
        "## 1. Executive summary",
        "",
        "This platform takes a patient's age, inflammatory biomarker level, pre-existing conditions, candidate dose "
        "and prior reaction history and produces a schema-validated safety report: eligible or not, a recommended "
        "dose, step-by-step reasoning, and the exact guideline sentences the decision rests on. Three layers of AI "
        f"work in sequence. A {NAMES[best]} classifier predicts adverse-reaction risk (test F1 {best_row.test_f1:.2f}, "
        f"ROC-AUC {best_row.test_roc_auc:.2f}). A retrieval index over the safety guideline supplies the relevant rules. "
        "A language model combines the two into structured JSON, which deterministic guardrails then check against "
        "the retrieved dose limits. A from-scratch self-attention module demonstrates the mechanism behind the "
        "language model on an mRNA sequence. The project shows how predictive ML, retrieval and generative AI hand "
        "off to each other in a regulated setting, with every step validated and every claim traceable to a source.",
        "",
        "## 2. Architecture",
        "",
        "```mermaid",
        "flowchart LR",
        "    CSV[(patient_records.csv)] --> M1[Module 1<br/>clean + classify]",
        "    M1 -->|risk label + probability| M4",
        "    SEQ[mRNA sequence] --> M2[Module 2<br/>self-attention]",
        "    TXT[(safety guidelines)] --> M3[Module 3<br/>chunk + embed + ChromaDB]",
        "    M3 -->|top-k excerpts| M4[Module 4<br/>LLM to JSON + guardrails]",
        "    M4 --> REP[[report .json + .md]]",
        "    M1 & M2 & M3 & M4 -.->|saved outputs| M5[Module 5<br/>dashboard]",
        "```",
        "",
        *module1_section(meta, comparison, weights),
        *module2_section(attention),
        *module3_section(manifest),
        *module4_section(generation),
        "## 7. Dashboard",
        "",
        f"![Dashboard]({FIG}/dashboard.png)",
        "",
        "Panel A: the classifier separates risk classes well above chance. Panel B: the attention pattern from "
        "Module 2. Panel C: average time per retrieval query versus per generated report; with a hosted LLM, "
        "generation dominates end-to-end latency.",
        "",
        *limitations_section(manifest),
        *reproduction_section(),
    ]
    DOCS_DIR.mkdir(exist_ok=True)
    # Never overwrite a report the student has edited (marker line removed).
    edited = REPORT_PATH.exists() and MARKER not in REPORT_PATH.read_text(encoding="utf-8")
    target = FRESH_PATH if edited else REPORT_PATH
    target.write_text("\n".join(lines), encoding="utf-8")
    return target


def run():
    path = build()
    if path == FRESH_PATH:
        print(f"docs/{REPORT_PATH.name} has been edited, so fresh numbers were written to docs/{FRESH_PATH.name}")
    else:
        print(f"Wrote docs/{REPORT_PATH.name} from the current outputs")
    return path


if __name__ == "__main__":
    run()
