def _words(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in STOPWORDS and len(w) > 2}


def _load():
    meta = json.loads(MODEL_META_PATH.read_text(encoding="utf-8"))
    comparison = pd.read_csv(METRICS_DIR / "model_comparison.csv")
    weights = pd.read_csv(METRICS_DIR / "final_model_feature_weights.csv")
    attention = json.loads(ATTENTION_META_PATH.read_text(encoding="utf-8"))
    manifest = json.loads((CHROMA_DIR / "index_manifest.json").read_text(encoding="utf-8"))
    generation = pd.read_csv(GENERATION_LOG_PATH)
    return meta, comparison, weights, attention, manifest, generation


